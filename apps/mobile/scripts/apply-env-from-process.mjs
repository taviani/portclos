#!/usr/bin/env node
/**
 * Write apps/mobile/.env from process env (Cursor Secrets / shell exports).
 * Never prints secret values. Used for local testing against production.
 *
 * Required:
 *   EXPO_PUBLIC_API_URL
 *   EXPO_PUBLIC_AUTH_ISSUER
 * Optional:
 *   EXPO_PUBLIC_AUTH_CLIENT_ID (default portclos)
 *   EXPO_OWNER, EXPO_PROJECT_ID (EAS)
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const out = path.join(root, '.env');

const required = ['EXPO_PUBLIC_API_URL', 'EXPO_PUBLIC_AUTH_ISSUER'];
const optional = [
  'EXPO_PUBLIC_AUTH_CLIENT_ID',
  'EXPO_OWNER',
  'EXPO_PROJECT_ID',
];

const missing = required.filter((k) => !process.env[k]?.trim());
if (missing.length) {
  console.error(
    `Missing env for production local test: ${missing.join(', ')}\n` +
      'Set them as Cursor Secrets (or export in the shell), same values as GitHub Actions / EAS.',
  );
  process.exit(1);
}

const api = process.env.EXPO_PUBLIC_API_URL.trim().replace(/\/$/, '');
const issuer = process.env.EXPO_PUBLIC_AUTH_ISSUER.trim().replace(/\/$/, '');
const clientId = (process.env.EXPO_PUBLIC_AUTH_CLIENT_ID || 'portclos').trim();

if (/localhost|127\.0\.0\.1/.test(api)) {
  console.error(
    'EXPO_PUBLIC_API_URL looks local — refuse start:prod. Use production HTTPS API URL.',
  );
  process.exit(1);
}
if (issuer.includes('example.com')) {
  console.error(
    'EXPO_PUBLIC_AUTH_ISSUER is still the placeholder — set the production OIDC issuer.',
  );
  process.exit(1);
}

const lines = [
  '# Generated by scripts/apply-env-from-process.mjs — do not commit',
  `EXPO_PUBLIC_API_URL=${api}`,
  `EXPO_PUBLIC_AUTH_ISSUER=${issuer}`,
  `EXPO_PUBLIC_AUTH_CLIENT_ID=${clientId}`,
];

for (const key of optional.slice(1)) {
  const v = process.env[key]?.trim();
  if (v) lines.push(`${key}=${v}`);
}

fs.writeFileSync(out, `${lines.join('\n')}\n`, { mode: 0o600 });
console.log(
  `Wrote ${path.relative(process.cwd(), out)} for production local test ` +
    `(API host: ${new URL(api).host}, issuer host: ${new URL(issuer).host})`,
);
